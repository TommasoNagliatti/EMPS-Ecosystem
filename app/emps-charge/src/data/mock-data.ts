export function getCharger(id: string) {
  return chargers.find((charger) => charger.id === id);
}

export function getStation(id: string) {
  return stations.find((station) => station.id === id);
}

export function getStationChargers(stationId: string) {
  return chargers.filter((charger) => charger.stationId === stationId);
}
